import { jsPDF } from 'jspdf';
import { FormulaEntry } from '@/types/formula';
import { latexToAscii } from '@/utils/mathSanitizer';

/**
 * Generates an EasyEquate laboratory-grade printable PDF formula sheet
 * Adhering to the Black (#131313), Brown (#5D4037), and White (#FFFFFF) palette.
 */
export function exportFormulaSheetPdf(formulas: FormulaEntry[], title: string = 'EasyEquate Formula Reference Sheet') {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'pt',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 40;
  let y = margin;

  // Header Banner
  doc.setFillColor(93, 64, 55); // #5D4037
  doc.rect(margin, y, pageWidth - margin * 2, 40, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.text('EASYEQUATE', margin + 14, y + 25);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.text(title.toUpperCase(), pageWidth - margin - 14, y + 25, { align: 'right' });

  y += 55;

  // Subtitle / metadata
  doc.setTextColor(19, 19, 19);
  doc.setFontSize(9);
  doc.text(`Curated Reference Sheet • ${formulas.length} Formulas • Generated by easyequate.com`, margin, y);
  y += 18;

  // Horizontal divider
  doc.setDrawColor(224, 224, 224);
  doc.setLineWidth(1);
  doc.line(margin, y, pageWidth - margin, y);
  y += 18;

  // Formula Cards / Rows
  formulas.forEach((f, idx) => {
    // Check if new page is needed
    if (y > pageHeight - 75) {
      doc.addPage();
      y = margin;

      // Repeat mini header
      doc.setFillColor(93, 64, 55);
      doc.rect(margin, y, pageWidth - margin * 2, 22, 'F');
      doc.setTextColor(255, 255, 255);
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(10);
      doc.text('EASYEQUATE FORMULA SHEET (CONT.)', margin + 10, y + 15);
      y += 35;
    }

    // Card background box
    doc.setFillColor(250, 250, 250);
    doc.setDrawColor(224, 224, 224);
    doc.roundedRect(margin, y, pageWidth - margin * 2, 48, 4, 4, 'FD');

    // Title & Category tag
    doc.setTextColor(19, 19, 19);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10);
    doc.text(`${idx + 1}. ${f.name}`, margin + 10, y + 16);

    doc.setTextColor(93, 64, 55);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    const categoryTag = `[${f.category.toUpperCase()}${f.level ? ` • ${f.level.toUpperCase()}` : ''}]`;
    doc.text(categoryTag, pageWidth - margin - 10, y + 16, { align: 'right' });

    // Formula Text (Sanitized ASCII representation for high-fidelity printing)
    const cleanFormula = latexToAscii(f.latex);
    doc.setFont('courier', 'bold');
    doc.setFontSize(10);
    doc.setTextColor(93, 64, 55);
    doc.text(cleanFormula, margin + 14, y + 32);

    // Description text
    doc.setFont('helvetica', 'italic');
    doc.setFontSize(8);
    doc.setTextColor(117, 117, 117);
    const desc = f.description.length > 80 ? f.description.slice(0, 77) + '...' : f.description;
    doc.text(desc, margin + 14, y + 43);

    y += 54;
  });

  // Footer on final page
  doc.setTextColor(117, 117, 117);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.text('EasyEquate — All-in-One Step-by-Step Math & Graphing Studio • https://easyequate.com', margin, pageHeight - 20);

  // Save PDF
  doc.save('EasyEquate-Formula-Sheet.pdf');
}
